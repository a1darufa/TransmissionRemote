namespace StringCatalogConverter.Tests;

/// <summary>The generated C# class that names every string for the app's code and XAML.</summary>
[TestClass]
public sealed class CodeWriterTests
{
    [TestMethod]
    public void EachStringBecomesAProperty()
    {
        var code = CodeWriter.Write([Resource("ShowLogFiles", "Show Log Files")]);

        StringAssert.Contains(code, "/// <summary>Show Log Files</summary>");
        StringAssert.Contains(code, """public static string ShowLogFiles => StringResources.Get("ShowLogFiles");""");
        StringAssert.Contains(code, "namespace TransmissionRemote.App;");
        StringAssert.StartsWith(code, "// <auto-generated>");
    }

    [TestMethod]
    public void APluralStringBecomesOneMethodForAllItsForms()
    {
        var code = CodeWriter.Write(
        [
            Resource("Files_One", "{0} file"),
            Resource("Files_Other", "{0} files"),
        ]);

        StringAssert.Contains(code,
            """public static string FilesFor(long count) => StringResources.PluralForm("Files", count);""");
        StringAssert.Contains(code, "/// <summary>The form for a count of: {0} files</summary>");
        Assert.DoesNotContain("Files_One", code);
    }

    [TestMethod]
    public void AStringAndAPluralWithTheSameWordsBothGetMembers()
    {
        // The namer keeps "Files" and "%lld files" apart, so the generated names must too.
        var code = CodeWriter.Write(
        [
            Resource("Files", "Files"),
            Resource("Files_One", "{0} file"),
            Resource("Files_Other", "{0} files"),
        ]);

        StringAssert.Contains(code, "public static string Files =>");
        StringAssert.Contains(code, "public static string FilesFor(long count)");
    }

    [TestMethod]
    public void NamesThatWouldClashStopTheConversion()
    {
        var error = Assert.ThrowsExactly<InvalidDataException>(() => CodeWriter.Write(
        [
            Resource("FilesFor", "Files for"),
            Resource("Files_Other", "{0} files"),
        ]));

        StringAssert.Contains(error.Message, "FilesFor");
    }

    [TestMethod]
    public void DocCommentsAreEscapedAndOnOneLine()
    {
        var code = CodeWriter.Write([Resource("Peers", "<b>Peers</b> & seeds\nsecond line")]);

        StringAssert.Contains(code, "/// <summary>&lt;b&gt;Peers&lt;/b&gt; &amp; seeds second line</summary>");
    }

    [TestMethod]
    public void MembersAreSortedAndLinesEndInLineFeeds()
    {
        var code = CodeWriter.Write([Resource("Zebra", "Zebra"), Resource("Apple", "Apple")]);

        Assert.IsLessThan(code.IndexOf("Zebra =>", StringComparison.Ordinal),
            code.IndexOf("Apple =>", StringComparison.Ordinal));
        Assert.DoesNotContain("\r", code);
        StringAssert.EndsWith(code, "}\n");
    }

    private static ResourceString Resource(string name, string value) => new(name, value, "Mac key: " + value);
}
