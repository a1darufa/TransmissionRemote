using System.Security;
using System.Text;
using TransmissionKit;

namespace StringCatalogConverter;

/// <summary>
/// Writes the C# class that names every string for the app: <c>Strings.ShowLogFiles</c> in code and
/// <c>{x:Bind app:Strings.ShowLogFiles}</c> in XAML. A string that is renamed or removed then breaks the build
/// instead of showing an empty label.
/// </summary>
/// <remarks>
/// A plural string becomes a method that picks the form for a count (<c>Strings.FilesFor(3)</c> for
/// <c>Files_One</c>, <c>Files_Other</c>, ...). The app's <c>StringResources</c> class does the loading.
/// </remarks>
internal static class CodeWriter
{
    public const string Namespace = "TransmissionRemote.App";

    private const string PluralMethodSuffix = "For";

    /// <summary>Writes the class from the default language's resources, which include every name.</summary>
    /// <exception cref="InvalidDataException">Two strings would get the same member name.</exception>
    public static string Write(IReadOnlyList<ResourceString> englishResources)
    {
        var members = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var (family, other) in PluralFamilies(englishResources))
        {
            Add(members, family + PluralMethodSuffix,
                $"""
                    /// <summary>The form for a count of: {DocText(other.Value)}</summary>
                    public static string {family}{PluralMethodSuffix}(long count) => StringResources.PluralForm("{family}", count);
                """);
        }
        foreach (var resource in englishResources.Where(resource => PluralFamily(resource.Name) is null))
        {
            Add(members, resource.Name,
                $"""
                    /// <summary>{DocText(resource.Value)}</summary>
                    public static string {resource.Name} => StringResources.Get("{resource.Name}");
                """);
        }

        var code = new StringBuilder();
        code.Append($$"""
            // <auto-generated>
            //   Written by Windows/tools/StringCatalogConverter from the String Catalogs. Don't edit it: change a
            //   catalog and run the converter again (Windows/README.md, "Strings").
            // </auto-generated>

            namespace {{Namespace}};

            /// <summary>Every interface string by name, in the user's language.</summary>
            internal static class Strings
            {

            """);
        code.AppendJoin("\n\n", members.Values);
        code.Append("\n}\n");
        return code.ToString().ReplaceLineEndings("\n");
    }

    /// <summary>"Files" for "Files_Few"; null for a name that isn't a plural form.</summary>
    internal static string? PluralFamily(string name) => Enum.GetValues<PluralCategory>()
        .Select(category => $"_{category}")
        .Where(suffix => name.EndsWith(suffix, StringComparison.Ordinal))
        .Select(suffix => name[..^suffix.Length])
        .FirstOrDefault();

    /// <summary>Each plural family with its "other" form, which English always has, for the doc comment.</summary>
    private static IEnumerable<(string Family, ResourceString Other)> PluralFamilies(
        IReadOnlyList<ResourceString> resources) =>
        resources
            .Where(resource => resource.Name.EndsWith($"_{PluralCategory.Other}", StringComparison.Ordinal))
            .Select(resource => (PluralFamily(resource.Name)!, resource));

    private static void Add(SortedDictionary<string, string> members, string name, string member)
    {
        if (!members.TryAdd(name, member))
        {
            throw new InvalidDataException(
                $"Two strings would both be called {name} in the generated code. Rename one of them.");
        }
    }

    /// <summary>The English text on one line, escaped for an XML doc comment.</summary>
    private static string DocText(string value) =>
        SecurityElement.Escape(value.ReplaceLineEndings(" ")) ?? string.Empty;
}
